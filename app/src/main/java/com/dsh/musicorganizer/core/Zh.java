    /** 「乾」读 qián 时保留（乾隆 / 乾坤），读 gān 时转「干」。 */
    private static final String[] KEEP_QIAN = {"乾隆", "乾坤", "乾卦", "乾陵"};
    /** 「著」读 zhù 时保留，读 zhe 时转「着」。 */
    private static final String[] KEEP_ZHU = {
            "著作", "著名", "著述", "著者", "著書", "著稱", "著錄", "土著",
    };
    /** 「徵」在五声音阶里保留。 */
    private static final String[] KEEP_ZHENG = {"徵羽", "角徵", "宮徵"};

    /** 这段文本看着像日文吗（含假名）。是的话整体不转换。 */
    public static boolean isJapanese(String text) {
        if (text == null) {
            return false;
        }
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c >= 0x3040 && c <= 0x30FF) {
                return true;   // 平假名 / 片假名
            }
            if (c >= 0xFF66 && c <= 0xFF9D) {
                return true;   // 半角片假名
            }
        }
        return false;
    }

    /** 里面有没有需要转换的繁体字（快速判断，给「要不要提示已转简体」用）。 */
    public static boolean hasTraditional(String text) {
        if (text == null) {
            return false;
        }
        for (int i = 0; i < text.length(); i++) {
            if (MAP.containsKey(Character.valueOf(text.charAt(i)))) {
                return true;
            }
        }
        return false;
    }

    /**
     * 繁体转简体。null 安全；已经是简体 / 日文 / 纯英文都原样返回。
     *
     * <p>时间轴（{@code [00:12.34]}）、标点、英文、emoji 全部原样保留 ——
     * 转换器只碰「表里有的那个汉字」，不做任何其它改写。
     */
    public static String toSimplified(String text) {
        if (text == null) {
            return "";
        }
        if (text.isEmpty() || isJapanese(text)) {
            return text;
        }
        StringBuilder sb = null;
        int n = text.length();
        int i = 0;
        while (i < n) {
            String forced = forcedAt(text, i);
            if (forced != null) {
                if (sb == null) {
                    sb = new StringBuilder(n);
                    sb.append(text, 0, i);
                }
                sb.append(forced);
                i += 2;
                continue;
            }
            char c = text.charAt(i);
            Character simplified = MAP.get(Character.valueOf(c));
            if (simplified == null || keepOriginal(c, text, i)) {
                if (sb != null) {
                    sb.append(c);
                }
            } else {
                if (sb == null) {
                    sb = new StringBuilder(n);
                    sb.append(text, 0, i);
                }
                sb.append(simplified.charValue());
            }
            i++;
        }
        return sb == null ? text : sb.toString();
    }

    /** 命中的固定词替换结果；没有返回 null。 */
    private static String forcedAt(String text, int i) {
        for (String[] f : FORCE) {
            if (text.startsWith(f[0], i)) {
                return f[1];
            }
        }
        return null;
    }

    /** 这个字在这个上下文里是否要保持原样（一对多的字）。 */
    private static boolean keepOriginal(char c, String text, int i) {
        switch (c) {
            case '乾':
                return startsAny(text, i, KEEP_QIAN);
            case '著':
                return startsAny(text, i, KEEP_ZHU);
            case '徵':
                return startsAny(text, i, KEEP_ZHENG);
            default:
                return false;
        }
    }

    private static boolean startsAny(String text, int i, String[] words) {
        for (String w : words) {
            if (text.startsWith(w, i)) {
                return true;
            }
        }
        return false;
    }
