/// 固定词替换：这些词里的字单独看会转错（「藉」默认不转）。
const List<List<String>> _force = <List<String>>[
  <String>['藉口', '借口'],
  <String>['憑藉', '凭借'],
  <String>['藉此', '借此'],
  <String>['藉由', '借由'],
  <String>['藉故', '借故'],
  <String>['藉機', '借机'],
  <String>['藉著', '借着'],
  <String>['藉端', '借端'],
];

/// 「乾」读 qián 时保留（乾隆 / 乾坤），读 gān 时转「干」。
const List<String> _keepQian = <String>['乾隆', '乾坤', '乾卦', '乾陵'];
/// 「著」读 zhù 时保留，读 zhe 时转「着」。
const List<String> _keepZhu = <String>['著作', '著名', '著述', '著者', '著書', '著稱', '著錄', '土著'];
/// 「徵」在五声音阶里保留。
const List<String> _keepZheng = <String>['徵羽', '角徵', '宮徵'];

final Map<int, int> _map = _buildMap();

/// 把字表拆成 codeUnit → codeUnit 映射（一次性）。
Map<int, int> _buildMap() {
  final Map<int, int> m = <int, int>{};
  final List<int> cs = _pairs.codeUnits;
  for (int i = 0; i + 1 < cs.length; i += 2) {
    m[cs[i]] = cs[i + 1];
  }
  return m;
}

/// 繁 → 简 转换入口（与旧版同名 API）。
abstract final class Zh {
  /// 这段文本看着像日文吗（含假名）。是的话整体不转换。
  static bool isJapanese(String? text) {
    if (text == null) return false;
    for (final int c in text.codeUnits) {
      if ((c >= 0x3040 && c <= 0x30FF) || (c >= 0xFF66 && c <= 0xFF9D)) {
        return true; // 平假名 / 片假名 / 半角片假名
      }
    }
    return false;
  }

  /// 里面有没有需要转换的繁体字（快速判断，给「要不要提示已转简体」用）。
  static bool hasTraditional(String? text) {
    if (text == null) return false;
    for (final int c in text.codeUnits) {
      if (_map.containsKey(c)) return true;
    }
    return false;
  }

  /// 繁体转简体。null 安全；已是简体 / 日文 / 纯英文原样返回。
  ///
  /// 时间轴、标点、英文、emoji 全部原样保留 —— 只碰「表里有的那个汉字」。
  static String toSimplified(String? text) {
    if (text == null) return '';
    if (text.isEmpty || isJapanese(text)) return text;
    StringBuffer? sb;
    final int n = text.length;
    int i = 0;
    while (i < n) {
      final String? forced = _forcedAt(text, i);
      if (forced != null) {
        sb ??= StringBuffer(text.substring(0, i));
        sb.write(forced);
        i += 2;
        continue;
      }
      final int c = text.codeUnitAt(i);
      final int? simplified = _map[c];
      if (simplified == null || _keepOriginal(c, text, i)) {
        if (sb != null) sb.writeCharCode(c);
      } else {
        sb ??= StringBuffer(text.substring(0, i));
        sb.writeCharCode(simplified);
      }
      i++;
    }
    return sb == null ? text : sb.toString();
  }

  /// 命中的固定词替换结果；没有返回 null。
  static String? _forcedAt(String text, int i) {
    for (final List<String> f in _force) {
      if (text.startsWith(f[0], i)) return f[1];
    }
    return null;
  }

  /// 这个字在这个上下文里是否要保持原样（一对多的字）。
  static bool _keepOriginal(int c, String text, int i) {
    switch (String.fromCharCode(c)) {
      case '乾':
        return _startsAny(text, i, _keepQian);
      case '著':
        return _startsAny(text, i, _keepZhu);
      case '徵':
        return _startsAny(text, i, _keepZheng);
      default:
        return false;
    }
  }

  static bool _startsAny(String text, int i, List<String> words) {
    for (final String w in words) {
      if (text.startsWith(w, i)) return true;
    }
    return false;
  }
}
